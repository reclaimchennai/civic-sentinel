export default function LoginPage() {
  const handleLogin = (providerId: string) => {
    if (providerId === "credentials") {
      signIn("credentials", { username: "demo", callbackUrl: "/" });
    } else {
      signIn(providerId, { callbackUrl: "/" });
    }
  };

  return (
    <main className="min-h-screen bg-black text-white flex items-center justify-center p-6">
      <Card className="w-full max-w-md bg-zinc-900 border-zinc-800">
        <CardHeader className="text-center">
          <CardTitle className="text-2xl font-bold text-white">Welcome Back</CardTitle>
          <CardDescription className="text-zinc-400">Sign in to report violations and earn rewards</CardDescription>
        </CardHeader>
        <CardContent className="grid gap-3">
          {providers.map((provider) => {
            const Icon = provider.icon;
            return (
              <Button
                key={provider.id}
                variant="ghost"
                className={`w-full h-12 justify-start gap-3 rounded-lg font-semibold ${provider.className}`}
                onClick={() => handleLogin(provider.id)}
              >
                <Icon className="w-5 h-5 shrink-0" />
                <span className="flex-1 text-center">{provider.label}</span>
              </Button>
            );
          })}
        </CardContent>
      </Card>
    </main>
  );
}
